import pandas as pd
df = pd.read_csv('clean_table.csv')
display(df)

from statsmodels.stats.proportion import proportions_ztest

# Separate Control and Test rows
control = df.iloc[0]
test = df.iloc[1]
purchase_count = [control['Purchases'], test['Purchases']]
total_impressions = [control['Impressions'], test['Impressions']]

z_cvr, p_cvr = proportions_ztest(purchase_count, total_impressions)

# 2. Post-click CVR (Purchases / Website Clicks)
purchase_count = [control['Purchases'], test['Purchases']]
total_clicks = [control['Website_Clicks'], test['Website_Clicks']]

z_click, p_click = proportions_ztest(purchase_count, total_clicks)
print("Overall CVR")
print("Z-statistic:", z_cvr)
print("P-value:", p_cvr)

print("\nPost-click CVR")
print("Z-statistic:", z_click)
print("P-value:", p_click)

"""
## Two-Proportion Z-Test (Overall CVR & Post-click CVR)

### 1. Import the statistical function
```python
from statsmodels.stats.proportion import proportions_ztest
```
Imports the function that performs a two-proportion z-test.

### 2. Select Control and Test rows
```python
control = df.iloc[0]
test = df.iloc[1]
```
`.iloc` selects rows based on their integer position.

- `df.iloc[0]` → selects the first row (Control).
- `df.iloc[1]` → selects the second row (Test).

We store these rows in separate variables for easier access.

### 3. Overall CVR

```python
purchase_count = [control['Purchases'], test['Purchases']]
total_impressions = [control['Impressions'], test['Impressions']]
```

We're creating two Python lists:

- `purchase_count` = number of purchases in each group.
- `total_impressions` = total impressions in each group.

Using our data, they look like:

```python
purchase_count = [15161, 14869]
total_impressions = [3177233, 2123249]
```

In statistical terminology:

- `purchase_count` = successes.
- `total_impressions` = number of observations (trials).

Remember:

CVR = Purchases / Impressions

### 4. Perform the Z-test

```python
z_cvr, p_cvr = proportions_ztest(purchase_count, total_impressions)
```

This is an example of **multiple variable assignment (unpacking)**.

The function returns two values:

1. Z-statistic
2. P-value

Python assigns them respectively to:

- `z_cvr` → stores the Z-statistic.
- `p_cvr` → stores the P-value.

It's equivalent to:

```python
result = proportions_ztest(purchase_count, total_impressions)

z_cvr = result[0]
p_cvr = result[1]
```

### 5. Post-click CVR

```python
purchase_count = [control['Purchases'], test['Purchases']]
total_clicks = [control['Website_Clicks'], test['Website_Clicks']]

z_click, p_click = proportions_ztest(purchase_count, total_clicks)
```

The process is exactly the same.

The only difference is the denominator:

- Overall CVR → Impressions.
- Post-click CVR → Website Clicks.

### 6. Display results

```python
print("Overall CVR")
print("Z-statistic:", z_cvr)
print("P-value:", p_cvr)

print("\nPost-click CVR")
print("Z-statistic:", z_click)
print("P-value:", p_click)
```

- `print()` displays the output.
- `\n` adds a line break for cleaner formatting.

### Summary

| Input | Meaning |
|---|---|
| `purchase_count` | Number of successes |
| `total_impressions` / `total_clicks` | Number of trials |
| `z_cvr` / `z_click` | How large the observed difference is relative to expected random variation |
| `p_cvr` / `p_click` | Evidence against the null hypothesis |

**Complete flow:** Select data → Prepare success counts and total trials → Run test → Interpret results.
"""

import pandas as pd
from scipy.stats import ttest_ind

daily = pd.read_csv("daily_cpa.csv")

control = daily.loc[daily["Group"] == "Control", "Daily_CPA"]
test = daily.loc[daily["Group"] == "Test", "Daily_CPA"]

print("Control Mean CPA:", round(control.mean(), 2))
print("Test Mean CPA:", round(test.mean(), 2))

t, p = ttest_ind(control, test, equal_var=False)

print("T-statistic:", round(t, 2))
print("P-value:", p)

